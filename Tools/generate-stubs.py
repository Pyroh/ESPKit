"""Generates Sources/ESPDevice/BundledStubs.swift from the JSON files of an esp-flasher-stub release.

Usage:
    python3 -I Tools/generate-stubs.py <version> <folder holding the <chip>.json files>

The JSON files are downloaded from https://github.com/espressif/esp-flasher-stub/releases
(MIT OR Apache-2.0). They are copied verbatim: ESPKit only reads the base segments
(text, data, addresses, entry) and ignores the plugins.
"""

import json
import pathlib
import sys

# Release file -> ChipFamily case. esp32p4-rev1.json (P4 before revision 3) is not
# bundled: selecting by revision will come with chipInfo().
CHIPS = {
    "esp8266": "esp8266",
    "esp32": "esp32",
    "esp32s2": "esp32s2",
    "esp32s3": "esp32s3",
    "esp32s31": "esp32s31",
    "esp32c2": "esp32c2",
    "esp32c3": "esp32c3",
    "esp32c5": "esp32c5",
    "esp32c6": "esp32c6",
    "esp32c61": "esp32c61",
    "esp32h2": "esp32h2",
    "esp32h21": "esp32h21",
    "esp32h4": "esp32h4",
    "esp32p4": "esp32p4",
}


def main() -> None:
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    version, folder = sys.argv[1].lstrip("v"), pathlib.Path(sys.argv[2])
    root = pathlib.Path(__file__).resolve().parent.parent
    lines = [
        "// SPDX-License-Identifier: MIT OR Apache-2.0",
        "//",
        f"// Generated by Tools/generate-stubs.py from esp-flasher-stub v{version}. Do not edit.",
        "// esp-flasher-stub: Copyright (c) 2025 Espressif Systems (Shanghai) CO LTD, MIT OR Apache-2.0.",
        "// https://github.com/espressif/esp-flasher-stub",
        "",
        "import ESPTargets",
        "",
        "extension StubImage {",
        f'    static let bundledVersion = "{version}"',
        "",
        "    static func bundledJSON(for chip: ChipFamily) -> String? {",
        "        switch chip {",
    ]
    for name, case in CHIPS.items():
        text = (folder / f"{name}.json").read_text()
        json.loads(text)  # rejects an unreadable file
        if '"""###' in text:
            sys.exit(f"{name}.json contains a raw string delimiter")
        lines.append(f"        case .{case}:")
        # Multi-line raw string: the JSON is copied byte for byte, without indentation.
        lines.append('            ###"""')
        lines.append(text.strip())
        lines.append('"""###')
    lines += [
        "        default:",
        "            nil",
        "        }",
        "    }",
        "}",
        "",
    ]
    out = root / "Sources" / "ESPDevice" / "BundledStubs.swift"
    out.write_text("\n".join(lines))
    print(f"{out.relative_to(root)}: {len(CHIPS)} stubs, {out.stat().st_size} bytes")


if __name__ == "__main__":
    main()
